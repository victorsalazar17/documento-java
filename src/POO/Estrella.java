package POO;

public class Estrella {

    public String color;
    public double ancho;
    public double alto;
    public double radio;
    public int numeroDePuntas;
    public String tipoEstrella;
    public boolean tieneBrillo;
    public String posicion;
    public String material;
    public double masa;
    public String nombre;


    public Estrella(String color, double ancho, double alto, double radio, int numeroDePuntas, String tipoEstrella, boolean tieneBrillo, String posicion, String material, double masa, String nombre) {
        this.color = color;
        this.ancho = ancho;
        this.alto = alto;
        this.radio = radio;
        this.numeroDePuntas = numeroDePuntas;
        this.tipoEstrella = tipoEstrella;
        this.tieneBrillo = tieneBrillo;
        this.posicion = posicion;
        this.material = material;
        this.masa = masa;
        this.nombre = nombre;
    }
}
